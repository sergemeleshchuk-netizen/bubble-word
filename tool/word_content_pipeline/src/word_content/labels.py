"""Форма надписи: называет ли она тему или только признак.

Одно правило, нужное в двух местах, — поэтому оно живёт отдельно: генератор
таким правилом отбирает контент, оценщик им же штрафует готовый уровень. Если
завести две копии, они разойдутся, и пакет начнёт проходить отбор и падать на
оценке.

Что именно проверяется. Надпись STRETCHY THINGS не называет тему — она называет
признак, придуманный ради четвёрки. Игрок такую группу не угадывает по словам,
он добирает её последней, по остатку. То же с PLUMBING WORDS, OFFICE SKILLS,
KINDS OF FOREST: головное слово ничего не именует.

Замер, ради которого правило появилось: на двадцати уровнях записи оригинала
такая надпись ровно одна из 188 (GEOGRAPHICAL OBJECTS), в нашем ремейке той же
двадцатки — 33 из 192. По шкале фана это −1 за каждую, до −2 на уровень, то
есть полтора балла из десяти, потерянных на одних названиях.

Широкая надпись натужной НЕ считается: FOOD, SCHOOL, MUSIC, DOCTOR — законные
имена тем, и в записи они работают. Разница между широким и пустым именно в
том, называет ли слово вещь.
"""

from __future__ import annotations

# Головные слова, которые ничего не именуют: любая четвёрка может оказаться
# «вещами», «словами» или «действиями».
VAGUE_HEADS: frozenset[str] = frozenset(
    {
        "THINGS",
        "STUFF",
        "WORDS",
        "TERMS",
        "ACTIONS",
        "ACTIVITIES",
        "SKILLS",
        "ITEMS",
        "OBJECTS",
    }
)

# Начало надписи, которое переносит смысл на следующее слово и обычно означает
# формулировку через классификацию: KINDS OF FOREST вместо FORESTS.
VAGUE_PREFIXES: tuple[str, ...] = ("KINDS OF ", "TYPES OF ", "SORTS OF ")


def is_vague(label: str | None) -> bool:
    """True, если надпись называет признак вместо темы."""
    name = (label or "").upper().strip()
    if not name:
        return False
    if name.startswith(VAGUE_PREFIXES):
        return True
    return name.split()[-1] in VAGUE_HEADS
