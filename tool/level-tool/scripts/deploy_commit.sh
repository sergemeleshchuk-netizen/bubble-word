#!/usr/bin/env bash
#
# Деплой сайта из КОММИТА, а не из рабочей папки, с тремя отказами до публикации.
#
# Зачем: `npx surge ./site` выкладывает каталог, как он лежит на диске. Над
# проектом работают несколько сессий в ОДНОМ рабочем каталоге и в нескольких
# worktree — ветка git их не изолирует, — поэтому обычный деплой уносил на
# продакшен чужие незакоммиченные правки и временные файлы.
#
# Здесь коммит выкладывается через временный git worktree: в нём лежит ровно то,
# что закоммичено, без чужих правок и без неотслеживаемых файлов.
#
# Чего первой версии этого скрипта НЕ хватило (03.08, разбор потери выкладки).
# Публикация из коммита закрыла «чужой мусор», но не закрыла «чужой ref»: три
# сессии выкладывали три разных ref — свою ветку, свой worktree и main, — и кто
# публиковал последним, тот и оставался на сайте. Инструмент откатывался с 1.31.0
# до 1.27.2 при полностью целой истории git. Поэтому теперь скрипт ОТКАЗЫВАЕТСЯ
# публиковать, когда:
#
#   1) в выкладываемом ref нет коммитов какой-то другой ветки или worktree —
#      публикация откатила бы чужую работу;
#   2) собранный `site/tool` в этом коммите собран НЕ из его же исходников —
#      именно так на сайт уехал бандл 1.27.2 при исходниках 1.31.0;
#   3) после публикации живой сайт отдаёт не тот бандл, что мы выложили.
#
# Обойти проверки 1 и 2 можно только явно: `FORCE=1`.
#
# Запуск:  bash scripts/deploy_commit.sh [ref] [domain]
#          npm run deploy:commit -- <ref>
#   ref     что выкладываем, по умолчанию HEAD (обычно main со всем слитым)
#   domain  куда, по умолчанию serge-mel.surge.sh
#   DRY=1   не публиковать, только показать, что уехало бы
#   FORCE=1 публиковать, несмотря на отказы 1 и 2
set -euo pipefail

REF="${1:-HEAD}"
DOMAIN="${2:-serge-mel.surge.sh}"

ROOT="$(git rev-parse --show-toplevel)"
SHA="$(git -C "$ROOT" rev-parse --short "$REF")"
TMP="$(mktemp -d)/site-$SHA"

cleanup() { git -C "$ROOT" worktree remove --force "$TMP" >/dev/null 2>&1 || true; }
trap cleanup EXIT

echo "деплой из коммита $SHA ($(git -C "$ROOT" log -1 --format=%s "$REF"))"

# --------------------------------------------------------------------------- #
# отказ 1: в этом ref нет чужой работы
# --------------------------------------------------------------------------- #
# Сравниваем со ВСЕМИ локальными ветками и с origin/main. Локальные — потому что
# сессии коммитят в свои ветки и в свои worktree и ничего не пушат: для origin
# этой работы не существует, а на сайте она бы пропала.
lost=""
for branch in $(git -C "$ROOT" for-each-ref --format='%(refname:short)' \
    refs/heads refs/remotes/origin/main); do
  behind="$(git -C "$ROOT" rev-list --count "$REF..$branch" 2>/dev/null || echo 0)"
  [ "$behind" = "0" ] && continue
  lost="${lost}  ${branch}: +${behind} коммит(ов)"$'\n'
  lost="${lost}$(git -C "$ROOT" log --format='      %h %s' -3 "$REF..$branch")"$'\n'
done

if [ -n "$lost" ]; then
  echo
  echo "ОТКАЗ: в $REF нет работы из других ветвей — публикация откатила бы её:"
  printf '%s' "$lost"
  echo "  Слейте их в $REF (git merge <ветка>) и повторите."
  echo "  Осознанно публикуете именно этот ref — FORCE=1."
  [ "${FORCE:-}" = "1" ] || exit 1
  echo "  FORCE=1 — продолжаю, несмотря на отказ."
fi

git -C "$ROOT" worktree add --detach "$TMP" "$REF" >/dev/null

# --------------------------------------------------------------------------- #
# отказ 2: собранный инструмент в коммите соответствует его исходникам
# --------------------------------------------------------------------------- #
# Собранный бандл коммитится (сайт обязан деплоиться без предварительной сборки),
# и именно поэтому он может отстать от исходников: пересобрать забыли, а версию
# подняли. Номер версии инструмента вшит в бандл — по нему и сверяем.
src_version="$(sed -n "s/.*TOOL_VERSION = '\([0-9][0-9.]*\)'.*/\1/p" \
  "$TMP/tool/level-tool/web/src/core/version.ts" 2>/dev/null || true)"
bundle="$(ls "$TMP"/site/tool/assets/index-*.js 2>/dev/null | head -1 || true)"

if [ -n "$src_version" ] && [ -n "$bundle" ]; then
  if grep -q "\"$src_version\"" "$bundle"; then
    echo "инструмент: исходники и собранный бандл сходятся на $src_version"
  else
    bundle_version="$(grep -o '"1\.[0-9][0-9]*\.[0-9]*"' "$bundle" | sort -u | tr -d '"' \
      | tr '\n' ' ')"
    echo
    echo "ОТКАЗ: в site/tool лежит бандл, собранный не из этих исходников."
    echo "  исходники: $src_version · в бандле: ${bundle_version:-версия не найдена}"
    echo "  Пересоберите и закоммитите: npm run build:site (в tool/level-tool)."
    echo "  Осознанно публикуете как есть — FORCE=1."
    [ "${FORCE:-}" = "1" ] || exit 1
    echo "  FORCE=1 — продолжаю, несмотря на отказ."
  fi
fi

if [ "${DRY:-}" = "1" ]; then
  echo "DRY=1, публикация пропущена. Содержимое site/ этого коммита:"
  find "$TMP/site" -maxdepth 2 -mindepth 1 | sed "s|$TMP/||" | sort
  exit 0
fi

npx --yes surge "$TMP/site" "$DOMAIN"

# --------------------------------------------------------------------------- #
# отказ 3: сайт отдаёт именно то, что выложили
# --------------------------------------------------------------------------- #
# Раньше «выложено» и «живо» расходились молча: деплой сообщал Success, а на
# домене оставалась прежняя сборка. Теперь это видно сразу и без ручной проверки.
want="$(basename "$bundle" 2>/dev/null || true)"
if [ -n "$want" ]; then
  sleep 3
  live="$(curl -s "https://$DOMAIN/tool/index.html" \
    | grep -o 'index-[A-Za-z0-9_-]*\.js' | head -1 || true)"
  if [ "$live" = "$want" ]; then
    echo "проверено на живом домене: инструмент $src_version ($live)"
  else
    echo "ВНИМАНИЕ: на домене бандл «${live:-не найден}», выкладывали «$want»."
    echo "  Либо кто-то опубликовал следом, либо кеш ещё не обновился."
    exit 1
  fi
fi
