/**
 * Источники контента для генератора.
 *
 * Инструмент собирает уровни из СНИМКА базы, а не из живой базы, — и снимок
 * не обязан быть один. Здесь их реестр.
 *
 * Рабочий источник — «Словарь игры» (`lexicon`): из него генератор собирает
 * уровни по умолчанию. Это самый широкий словарь проекта с нашей разметкой и
 * весами слов, и именно он отвечает за сдаваемые пакеты.
 *
 * Остальные два существуют ради проверяемости. Пока источник один, невозможно
 * отличить «генератор упёрся в свои правила» от «генератор упёрся в контент».
 * Авторская разметка — 1296 категорий, выращенных под эти самые правила: на ней
 * инструмент всегда выглядит хорошо, и это ничего не доказывает. Словарь
 * оригинала — 6714 категорий, которые никто под нас не подгонял, у половины
 * пул ровно четыре слова, медиана частотности на 0.4 zipf ниже нашей.
 * Тот же генератор, те же гейты, другой контент — и сразу видно, что в
 * инструменте настройка, а что подгонка. Второе назначение словаря оригинала —
 * демонстрация референс-уровней: уровни 1-1025 целевой игры, собранные нашим же
 * конвейером.
 *
 * Чего переключатель НЕ делает: он не смешивает источники НА ЛЕТУ. Уровень
 * собирается целиком из одного снимка, и хеш снимка входит в хеш уровня — по
 * пакету всегда видно, откуда он. Словарь игры собран заранее, отдельным
 * скриптом, в отдельный файл со своим хешем — то есть он такой же один снимок,
 * как остальные, а не переключатель «взять оттуда и отсюда».
 *
 * Решение владельца от 31.07 «чужой словарь в нашей базе не храним» здесь
 * соблюдено буквально: словарь оригинала лежит отдельным файлом
 * (`data/reference.snapshot.json`, сборка — `scripts/export_reference_snapshot.py`),
 * словарь игры — тоже отдельным (`data/lexicon.snapshot.json`, сборка —
 * `scripts/export_lexicon_snapshot.py`), а авторская разметка от их
 * существования не меняется ни на одну связь: сравните
 * `content.snapshot.sha256` до и после.
 */
/*
 * Здесь только описание источников и ни одного импорта данных: этот модуль
 * читают и браузер, и офлайн-скрипты, и тесты под node. JSON, импортированный
 * статически, node без флагов не разберёт, и реестр перестал бы быть общим.
 * Загрузка снимка живёт там, где известен способ его достать: в App.tsx —
 * импортом бандлера, в скриптах — чтением файла по `snapshotFile`.
 */

export type SourceId = 'production' | 'reference' | 'lexicon';

export interface ContentSource {
  id: SourceId;
  /** имя в переключателе */
  label: string;
  /** путь к снимку от корня tool/level-tool */
  snapshotFile: string;
  /** одна строка: что это за словарь */
  origin: string;
  /** абзац для экрана «База контента» */
  summary: string;
  /**
   * Чего у источника нет. Список обязателен: источник с меньшим числом слоёв
   * должен объявлять об этом сам, иначе разница между двумя прогонами
   * инструмента выглядит как разница в качестве генератора.
   */
  limits: string[];
  /** есть ли у источника журнал AI-прогонов и ревью (экран «AI-воркфлоу») */
  hasAiWorkflow: boolean;
}

