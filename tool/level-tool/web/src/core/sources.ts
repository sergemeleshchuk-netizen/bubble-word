/**
 * Источники контента для генератора.
 *
 * Инструмент собирает уровни из СНИМКА базы, а не из живой базы. Снимков два,
 * и это решение владельца от 03.08 — «оставить только две базы».
 *
 * **BADB** (`production`) — основная база проекта, из неё собираются уровни.
 * Костяк в ней — контент целевой игры: 5409 категорий, приехавших выгрузкой
 * 1025 сыгранных уровней. Наша разметка живёт в той же базе рядом (1297
 * категорий) и работает ОБОГАЩЕНИЕМ: даёт слова, значения, регистр, статусы
 * связей и правила там, где у выгрузки их нет, и служит материалом, чтобы
 * категорию конкурента усложнить, упростить или породить новую. Происхождение
 * каждой категории видно в базе полем `origin`, склейка перестала быть
 * производным файлом и стала самой базой (`tool/word_content_pipeline`).
 *
 * **RefBWJ** (`reference`) — уровни целевой игры как есть, только чтение.
 * Генерация на нём выключена: состав уровня задан выгрузкой, подбирать нечего.
 * Он нужен как эталон — наиграть оригинал в прототипе и сравнить с нашим.
 *
 * Чего переключатель НЕ делает: он не смешивает источники на лету. Уровень
 * собирается целиком из одного снимка, и хеш снимка входит в хеш уровня — по
 * пакету всегда видно, откуда он.
 *
 * Что было до 03.08. Источников было три: авторская разметка, словарь
 * оригинала и «словарь игры» — их склейка, которую собирал отдельный скрипт в
 * отдельный файл при каждой сборке. Склейку нельзя было править: любая правка
 * в ней жила до следующей пересборки. Поэтому контент конкурента импортирован
 * внутрь базы, а третий источник убран — он стал самой базой. Скрипт
 * `scripts/export_lexicon_snapshot.py` и его снимок оставлены в репозитории
 * как след того, как это считалось раньше, но инструментом не читаются.
 */
/*
 * Здесь только описание источников и ни одного импорта данных: этот модуль
 * читают и браузер, и офлайн-скрипты, и тесты под node. JSON, импортированный
 * статически, node без флагов не разберёт, и реестр перестал бы быть общим.
 * Загрузка снимка живёт там, где известен способ его достать: в App.tsx —
 * импортом бандлера, в скриптах — чтением файла по `snapshotFile`.
 */

export type SourceId = 'production' | 'reference';

export interface ContentSource {
  id: SourceId;
  /** имя в переключателе */
  label: string;
  /** путь к снимку от корня tool/level-tool */
  snapshotFile: string;
  /** одна строка: что это за словарь */
  origin: string;
  /** абзац для экрана «База контента» */
  summary: string;
  /**
   * Чего у источника нет. Список обязателен: источник с меньшим числом слоёв
   * должен объявлять об этом сам, иначе разница между двумя прогонами
   * инструмента выглядит как разница в качестве генератора.
   */
  limits: string[];
  /** есть ли у источника журнал AI-прогонов и ревью (экран «AI-воркфлоу») */
  hasAiWorkflow: boolean;
  /**
   * Роль источника, и она же — цвет выбранной кнопки в переключателе.
   *
   * Не косметика: на рабочем словаре собираются пакеты, которые мы сдаём, а на
   * тестовом лежат чужие уровни только для чтения. Спутать их дорого — пакет,
   * собранный не на том словаре, не воспроизводится, — поэтому выбранный
   * источник видно цветом: рабочий зелёный, тестовый жёлтый.
   */
  tone: 'live' | 'test';
}

