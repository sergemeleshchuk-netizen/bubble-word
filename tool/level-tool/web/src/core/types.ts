export interface LevelWord {
  text: string;
  /** 'word' — обычный пузырь; 'meta' — имя собранной категории */
  kind: 'word' | 'meta';
  /** ключ дочерней категории, если kind = meta */
  metaChild?: string;
  /**
   * Картинка вместо текста на пузыре: эмодзи (см. core/metaIcons.ts). Только
   * у мета-пузырей с простым именем, примерно у четверти таких на уровне.
   *
   * Слой отображения, а не личность пузыря: `text` остаётся словом, и всё
   * ядро — выкладка, решатель, ловушки, оценки — работает со словом. Поле
   * необязательное, поэтому уровни без картинок хешируются как прежде.
   */
  icon?: string;
  zipf: number | null;
  frequencyUnknown: boolean;
  relation?: string;
  fit?: number;
  obviousness?: number;
}

export interface LevelCategory {
  key: string;
  label: string;
  rule: string;
  theme: string;
  words: LevelWord[];
  /** глубина в мета-лесу: 0 — корень (никого не ждёт) */
  metaDepth: number;
  /** ключ родителя, если эта категория идёт словом в другую */
  parentKey: string | null;
  isQuickwin: boolean;
}

export interface Trap {
  word: string;
  /** категория, где слово действительно живёт */
  home: string;
  /** категория, куда правдоподобно тянет */
  decoy: string;
  homeObviousness: number;
  decoyFit: number;
  decoyObviousness: number;
}

export interface HalfSplit {
  word: string;
  home: string;
  fragments: [string, string];
  fragmentsAreWords: boolean;
}

export interface Chain {
  locksCategory: string;
  unlockedByCompleting: string;
}

/** Заблокированный пузырь (лёд или «?»): слово на старте поля и слоёв счётчика. */
export interface BlockedBubble {
  word: string;
  /** ключ категории, которой слово принадлежит */
  category: string;
  /** мерджей до разблокировки, 2-3 */
  layers: number;
}

/** Один пузырь выкладки: текст и категория, которой слово принадлежит. */
export interface DealBubble {
  word: string;
  /** ключ категории (`LevelCategory.key`) */
  category: string;
}

/**
 * Первая выкладка уровня: что лежит на поле на старте и в каком порядке
 * приходит досыпка. Правила и обоснование — в `core/deal.ts`.
 */
export interface Deal {
  /** пузыри на поле в момент старта */
  start: DealBubble[];
  /** очередь досыпки строго в этом порядке */
  queue: DealBubble[];
}

export interface LevelSpec {
  levelId: number;
  schemaVersion: string;
  board: {
    categoriesCount: number;
    wordsPerCategory: number;
    /** производное поле: 4 × категорий − мета (SPEC_AUDIT §1) */
    startBubbles: number;
    /** одновременно на поле; остальное досыпается (TARGET_GAME_OBSERVATIONS §5) */
    boardCapacity: number;
    moveFloor: number;
    /** null = без лимита ходов (туториальный первый уровень, как L1 референса) */
    moveLimit: number | null;
    moveLimitK: number | null;
    moveLimitPolicy: 'conservative';
    /**
     * Режим раздачи, которым посчитана выкладка (см. core/deal.ts). Хранится
     * в спеке, потому что выкладка обязана пересчитываться из одного спека
     * (`dealForSpec`); отсутствие поля = историческая раздача старых пакетов.
     */
    dealMinStartWords?: number;
    /** явная схема выкладки, если уровень собран по ней (сильнее минимума) */
    dealScheme?: number[];
    /**
     * Бюджет старта из таблицы декад: [пол приёмки, потолок поля]. Лежит в
     * спеке по той же причине, что и режим раздачи: выкладка обязана
     * пересчитываться из одного спека. Нет поля = старт упирается в
     * `boardCapacity`, как было до таблицы.
     */
    dealStartBubbles?: [number, number];
  };
  categories: LevelCategory[];
  /**
   * Первая выкладка. Часть уровня, а не дело клиента: см. `core/deal.ts`.
   * Входит в хеш уровня — уровень с другой выкладкой это другой уровень.
   */
  deal: Deal;
  traps: Trap[];
  halves: HalfSplit[];
  modifiers: {
    chains: Chain[];
    frozenBubbles: BlockedBubble[];
    hiddenBubbles: BlockedBubble[];
    /** цепь-линия поперёк поля; null — цепи нет */
    chainLine: { need: number } | null;
  };
}

