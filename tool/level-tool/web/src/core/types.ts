/** Статус связи. Порядок важен: индекс лежит в снимке. */
export const STATUS = {
  approved: 0,
  alternative: 1,
  hard_only: 2,
  candidate: 3,
  rejected: 4,
} as const;

export type StatusCode = 0 | 1 | 2 | 3 | 4;

/**
 * Готовность категории к автоматической сборке уровня. Считается на стороне
 * базы (`derive-readiness`), не здесь: это свойство контента, а не генератора.
 *   ready        — 4+ слов уровня approved/alternative, пул не перекошен
 *   constrained  — годится, но пул тонкий или перекошен в hard_only
 *   curated_only — только вручную собранные четвёрки (парное правило)
 *   hard_only    — нормальных слов нет, только сложные уровни
 *   blocked      — четвёрку не собрать даже со hard_only
 */
export type Readiness =
  | 'ready' | 'constrained' | 'curated_only' | 'hard_only' | 'blocked' | 'unknown';

export interface SnapshotCategory {
  /** ключ, стабильный идентификатор */
  k: string;
  /** отображаемое имя — оно же слово-пузырь, если категория мета-ребёнок */
  l: string;
  /** правило «что тут лежит» человеческими словами */
  r: string;
  /** доминирующий тип связи */
  rel: string;
  /** тематическая сфера */
  th: string;
  /** базовая сложность 0..1, может отсутствовать */
  d: number | null;
  /** готовность категории; в снимках 1.0 поля нет */
  rd?: Readiness;
  /**
   * Только источник «словарь оригинала»: сколько раз категория выходила в
   * выгрузке и на каком уровне впервые. У нашей базы такого прошлого нет —
   * поля необязательные, и читать их можно только зная источник.
   */
  ref_levels?: number;
  ref_first_level?: number;
  /**
   * Только словарь игры: откуда категория — индекс в `Snapshot.origins`
   * (0 наша, 1 оригинала, 2 обе). У одноисточниковых снимков поля нет, и это
   * правильно: там ответ известен заранее и хранить его значило бы дублировать
   * имя источника в каждой строке.
   */
  o?: 0 | 1 | 2;
}

export interface SnapshotWord {
  /** отображаемый текст */
  t: string;
  /** нормализованная форма — ключ идентичности */
  n: string;
  /** частотность zipf; null означает frequency_unknown (SPEC_AUDIT §13) */
  z: number | null;
  /** 1, если частотнику слово неизвестно */
  u: 0 | 1;
  /** 1, если строка — одиночная лемма нижнего регистра (lexicon_membership) */
  l: 0 | 1;
  /** 1, если имя собственное */
  p: 0 | 1;
  /**
   * Регистр слова: 0 бытовое, 1 пассивное, 2 специальное; null — не размечено.
   *
   * Проставляется суждением (`words.everyday_class`, шаг миграции 010), а не
   * выводится, потому что вывести не из чего: `congestion` 3.66 владелец
   * продукта отверг, `carrot` 3.62 безупречен, `omelet` 2.63 тоже — по
   * частотности эти группы не разделяются ни одним порогом. Средние по классам
   * всё же расходятся (3.97 / 3.29 / 2.92), но решает не среднее, а слово.
   */
  e?: 0 | 1 | 2 | null;
  /** число токенов */
  tok: number;
  /**
   * Вес слова 0..1: годится ли оно в уровень вообще. Только словарь игры
   * (снимок 2.1), у одноисточниковых снимков поля нет.
   *
   * Зачем понадобился. Главный фильтр словаря — регистр слова (`e`), но он
   * существует только у нашей базы: 8786 слов выгрузки оригинала нашей
   * разметки не имеют вовсе, и на них фильтр не работает ни для одного.
   * Вес — тот же фильтр, умеющий работать без разметки:
   *
   *   слово размечено   вес читается с регистра: 1.00 / 0.55 / 0.20;
   *   не размечено      вес ОЦЕНИВАЕТСЯ по числу уровней, которые слово
   *                     отработало у оригинала, и по частотности.
   *
   * Оценка проверена на 6369 словах, где известны обе величины: порог 0.70
   * даёт 83% бытовых слов, 0.80 — 88% при базовой доле 58%. То есть она
   * работает, но слабее разметки — поэтому оценке порог ставится выше
   * (`minWordWeight` в DecadeGates, decadeProfiles.ts). Формула и весь замер —
   * в scripts/export_lexicon_snapshot.py.
   */
  w?: number;
  /** 1, если вес оценён по уликам, а не прочитан с разметки регистра */
  we?: 0 | 1;
  /** только словарь игры: откуда слово, индекс в `Snapshot.origins` */
  o?: 0 | 1 | 2;
}

/** Связь в снимке: массив вместо объекта, чтобы снимок не раздувался. */
export type SnapshotMembership = [
  wordIndex: number,
  categoryIndex: number,
  status: StatusCode,
  fit: number,
  obviousness: number,
  relation: string,
  senseIndex: number | null,
  /** игровая сложность связи 0..1; отдельная ось от статуса (снимок 2.0) */
  gameplayDifficulty?: number | null,
  /** битовая маска risk-флагов по порядку Snapshot.risk_flags (снимок 2.0) */
  riskMask?: number,
  /**
   * Вес связи 0..1: насколько слово — ответ ИМЕННО этой категории (снимок 2.1).
   *
   * Не путать с весом слова (`SnapshotWord.w`): тот отвечает «годится ли слово
   * в уровень вообще» и работает допуском, этот — «какое из годных брать
   * первым» и работает порядком. Фильтровать им нельзя, и это не осторожность,
   * а замер: у словаря игры улика оригинала (доля выходов слова в четвёрках
   * категории) НЕ предсказывает наш статус связи — на 1948 общих связях
   * средняя улика у approved 0.32, у hard_only 0.43, то есть в обратную
   * сторону. Подробности — в scripts/export_lexicon_snapshot.py.
   */
  weight?: number,
  /** только словарь игры: чья это связь, индекс в `Snapshot.origins` */
  origin?: 0 | 1 | 2,
  /**
   * Место слова в пуле своей категории по популярности (снимок 2.2):
   * 0.0 — самое расхожее слово категории, 1.0 — самое редкое.
   *
   * Считает база (`rank-pools`), инструмент только исполняет. Пусто у пулов
   * до пяти слов — там выбирать не из чего — и у снимков, которые через
   * ранжирование не проходили.
   */
  poolRank?: number | null,
];

/**
 * Запрет на сочетание двух категорий в одном уровне.
 *
 * Решение принято на стороне контента: `derive-conflicts` считает пересечение
 * играбельных пулов и сохраняет пару с причиной. Генератор его исполняет, а не
 * пересчитывает — иначе одна и та же пара разрешена в базе и запрещена в
 * инструменте (или наоборот), и спорить будет нечем.
 */
export type SnapshotConflict = [
  categoryA: number,
  categoryB: number,
  /** индекс в Snapshot.conflict_types: do_not_pair | needs_disjoint_words */
  type: number,
  /** P0/P1/…, как решено в базе */
  severity: string | null,
  /** сколько играбельных слов у пулов общие */
  overlap: number,
];

/** Проверенная четвёрка: прошла solver единственности на стороне базы. */
export type SnapshotQuartet = [
  category: number,
  words: number[],
  /** индекс в Snapshot.quartet_tiers: easy | medium | hard | unranked */
  tier: number,
  /**
   * Место четвёрки среди четвёрок своей категории по популярности слов:
   * 0 — самая расхожая, 1 — самая редкая. null у категорий ровно из четырёх
   * слов, где выбирать не из чего. Тир — метка для глаза, место — число для
   * отбора: полосы `easy_max`/`medium_min`/`medium_max` лежат в constants, и
   * easy с medium намеренно перекрываются.
   */
  poolPosition?: number | null,
];

export interface Snapshot {
  schema_version: string;
  statuses: string[];
  /** порядок risk-флагов: индекс = бит в маске связи (снимок 2.0) */
  risk_flags?: string[];
  conflict_types?: string[];
  quartet_tiers?: string[];
  /** порядок происхождений: индекс лежит в полях `o`/`origin` (снимок 2.1) */
  origins?: string[];
  constants: {
    zipf_max: number; top50k_zipf: number; quickwin_zipf: number;
    /** границы тиров четвёрок по месту в пуле (снимок 2.2) */
    easy_max?: number; medium_min?: number; medium_max?: number;
  };
  categories: SnapshotCategory[];
  words: SnapshotWord[];
  senses: { word: number | null; key: string; def: string }[];
  memberships: SnapshotMembership[];
  /** категории, чьё имя существует в базе как слово: материал для мета-связей */
  meta_capable: { category: number; word: number; hosts: number[] }[];
  /** пары категорий, которые нельзя ставить в один уровень (снимок 2.0) */
  conflicts?: SnapshotConflict[];
  /** четвёрки, проверенные solver'ом базы (снимок 2.0) */
  quartets?: SnapshotQuartet[];
  content_snapshot_hash: string;
  stats?: Record<string, number>;
}

