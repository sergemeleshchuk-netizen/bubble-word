export type Modifier = 'chains' | 'halves' | 'ice' | 'hidden' | 'chain_line';

/**
 * Игровой модификатор уровня — один на партию (GDD §7).
 *
 * `none` — чистый словесный уровень. Остальные четыре — механики играбельного
 * прототипа: половинки (слово распилено на два пузыря), лёд и «?» (пузырь
 * заблокирован, тает от мерджей), цепь (линия делит поле, мердж поперёк
 * запрещён). Модификатор входит в спек и в игровой JSON: игра его исполняет,
 * оценка D учитывает, симулятор проходимости проигрывает.
 */
export type LevelModifier = 'none' | 'halves' | 'ice' | 'hidden' | 'chain_line';

export interface BlockConfig {
  /** диапазон номеров уровней, например [201, 210] */
  levelRange: [number, number];
  /** коридор по числу категорий */
  categoryCorridor: [number, number];
  /** позиции в блоке (1-based), где стоит спайк сложности */
  spikePositions: number[];
  /** позиции передышки */
  recoveryPositions: number[];
  /** целевое число редких слов (zipf < 3) на уровень */
  rarityRange: [number, number];
  /** максимальная глубина мета-леса */
  maxMetaDepth: number;
  /** разрешённые модификаторы */
  allowedModifiers: Modifier[];
  /** тематические сферы: включить / исключить */
  includeThemes: string[];
  excludeThemes: string[];
  /** темы, на которых просят ловушки */
  trapThemes: string[];
  /** окно свежести: слово не повторяется столько уровней */
  wordFreshnessWindow: number;
  /** окно свежести для имён категорий */
  categoryFreshnessWindow: number;
  /** слов в категории, дефолт 4 */
  wordsPerCategory: number;
  /** seed генерации */
  seed: string;
  /**
   * Явный план по позициям блока. Если задан — сильнее коридора и ролей.
   * Профиль блока задаётся настройками, а не кодом: пользователь меняет любую
   * строку, и генератор обязан ей подчиниться либо объяснить отказ.
   */
  categoryPlan?: number[];
  metaPlan?: number[];
  /**
   * Явный модификатор по позициям блока: `'none'` — выключить на этом уровне,
   * `null` — оставить на усмотрение плана (лесенка по декадам из `modifierFor`).
   *
   * Появилось вместе с чекбоксами на графике ритма. До них увидеть, что на
   * уровне включены половинки, можно было только в собранном уровне — то есть
   * после генерации, — а выключить их на ОДНОМ уровне было нельзя вовсе:
   * `allowedModifiers` работает на весь блок сразу.
   *
   * Поле необязательное, как и `decadeGates`: пока его нет, нормализованный
   * конфиг не меняется и хеш сдаваемого пакета остаётся прежним.
   */
  modifierPlan?: (LevelModifier | null)[];
  /**
   * Гейты декады: чем уровень 1-10 отличается от уровня 191-200 не размером,
   * а содержимым. Собираются из `DECADE_PROFILES` (см. decadeProfiles.ts).
   *
   * Поле необязательное сознательно: пресет блока 201-210 его не задаёт, поэтому
   * нормализованный конфиг для него не меняется и хеш сдаваемого пакета остаётся
   * прежним. Как только гейты заданы — они входят в хеш, потому что влияют
   * на контент.
   */
  decadeGates?: DecadeGates;
  /**
   * Минимум слов категории на стартовом поле (облегчённая раздача, см.
   * core/deal.ts). 2 = у категории на старте минимум пара, кому не хватило
   * места — целиком в очереди; одиночек-«мёртвых» пузырей нет. Не задано или
   * 1 = историческая ровная раздача «всем понемногу» — так пресет 201-210
   * сохраняет хеш сдаваемого пакета. Настраивается по промежуткам уровней
   * на первой вкладке инструмента (DEFAULT_DEAL_RANGES в decadeProfiles.ts).
   */
  dealMinStartWords?: number;
  /**
   * Явная схема выкладки старта: точные доли по убыванию, например
   * [4, 3, 3, 3, 2, 2, 2, 2, 1] — формат таблицы декад (см. docs/
   * DECADE_CALIBRATION.md и таблицу на первой вкладке). Сильнее
   * dealMinStartWords. Не задана — раздача считается автоматически.
   */
  dealScheme?: number[];
  /**
   * Вилка схем из таблицы декад: уровень с минимумом категорий коридора
   * получает min, с максимумом — max, между ними схема интерполируется
   * (resolveScheme в decadeProfiles.ts). Разрешённая для уровня схема
   * записывается в спек как board.dealScheme. Сильнее dealScheme.
   */
  dealSchemeRange?: { min: number[]; max: number[] };
  /**
   * Шаров-слов на старте: [минимум, максимум] на промежуток уровней.
   *
   * Замер записанных уровней оригинала: на L1-10 старт занимает 16-24 пузыря,
   * на L11-20 — 18-24, дальше выгрузка старта не содержит. То есть поле
   * доходит до полной вместимости постепенно, а первая декада встречает игрока
   * неполным полем. Раньше это было невыразимо: бюджет старта всегда упирался
   * в `BOARD_CAPACITY`, и уровень 1-10 из 12 категорий выкладывал те же 24
   * пузыря, что уровень 500-го.
   *
   * `max` — потолок бюджета старта, он и работает: поле заполняется до
   * `min(boardCapacity, max, всего пузырей)`. `min` — пол приёмки: столько
   * пузырей старт обязан набрать, если материала хватает (checkDeal).
   *
   * Вместимость поля (`boardCapacity`) при этом остаётся 24 всегда — это
   * физика поля, а не решение дизайнера: в оригинале 24 пузыря видны уже на
   * L7. Настраивается таблицей декад на первой вкладке.
   */
  dealStartBubbles?: [number, number];
  /**
   * Пресет инструмента: таблица стартовой раскладки его НЕ переписывает.
   *
   * Нужен потому, что пресет 201-210 — сдаваемый пакет с закреплённой формой
   * кривой (13-18 категорий, свой план по позициям), а таблица декад для этих
   * номеров задаёт коридор 8-12 и пересобрала бы план целиком. Раньше признаком
   * «не трогать» служило пустое `dealMinStartWords`, но это был признак другой
   * вещи — способа раздачи, — и он сломался, как только пресет перевели на
   * раздачу в глубину. В хеш поле НЕ входит: оно про поведение интерфейса,
   * а не про содержимое уровня.
   */
  presetLocked?: boolean;
}

export interface DecadeGates {
  /**
   * Потолок базовой сложности категории (поле `base_difficulty` базы, 0.1-0.6).
   *
   * База знает, что COLORS и FARM ANIMALS проще, чем UNIVERSITIES и LOCKSMITH
   * WORDS, — а генератор это поле не читал вовсе. Отсюда и жалоба на пакет
   * T1-T10: «простые якорные категории не взяты», уровень 1 собирался из
   * категорий d=0.4 при том, что в базе есть d=0.1.
   *
   * Числа не из референса: у референсных категорий нашего d нет. Это шкала базы —
   * ранние декады тяготеют к её нижней половине, поздние ко всей.
   *
   * Это ЦЕЛЬ, а не запрет: категории выше цели остаются доступны, просто ценятся
   * ниже при отборе. Жёстким фильтром на всю декаду быть нельзя — пробовал:
   * пул сужался настолько, что мета-пары кончались к концу декады (шесть декад
   * из двадцати уходили в хвост 0-0-2 при коридоре 3-6).
   */
  categoryDifficultyTarget: number;
  /**
   * Потолок для уровня-туториала — вот он жёсткий. На L1 оригинала лежат коровы,
   * цвета, машины, компас и дни недели; там нет места «сложной, но красивой»
   * категории, и пул из одной декады этот запрет выдерживает.
   */
  tutorialCategoryDifficultyMax: number;
  /** предел числа токенов в ответе: 1 = только однословные */
  maxTokens: number;
  /** предел длины слова в буквах */
  maxWordLen: number;
  /**
   * Целевая средняя длина слова в буквах — замер этой декады оригинала.
   *
   * Отдельная ось от частотности, и это главное. На уровне 12 медиана
   * частотности у нас 4.05 при цели декады 4.01 — попали; а средняя длина
   * 6.7 буквы против 6.2 у оригинала, и слов длиннее восьми букв 22% против
   * 12%. Жалоба «слишком сложные слова» пришла именно на это: `silverware`,
   * `ointment`, `neapolitan` читаются тяжело не потому, что редкие, а потому
   * что длинные. Потолок `maxWordLen` тут не помогает — он стоит на 13.
   */
  wordLenTarget: number;
  /** минимальный zipf для имени собственного */
  minProperNounZipf: number;
  /**
   * Пол частотности: ниже него слово в уровень не берётся вообще.
   *
   * До 02.08 такого запрета не было ни одного. Редкость слов существовала только
   * как ЦЕЛЬ (`rareTarget`, порог `zipf < 3.0`) — то есть как рычаг сложности,
   * которым можно добрать D. Пола не было, и это давало вот что: в сданном
   * пакете TOP ни одного слова ниже 3.0 нет, отчёт честно печатает «редких слов
   * 0», а на поле при этом лежат `quail` 3.13, `obituary` 3.41, `congestion`
   * 3.66, `veal` 3.08, `epoxy` 3.10, `tungsten` 3.12, `basilica` 3.08. Порог
   * стоял ровно там, где под него ничего не попадает, и метрика отчитывалась об
   * успехе. Владелец продукта посмотрел два уровня в прототипе и назвал эти
   * слова первыми.
   *
   * Замер базы под пол 3.75: связей выше порога 8923, категорий, способных дать
   * четвёрку целиком, — 931 из 1265, четвёрок без повтора слова 1773. Пакету из
   * 20 уровней нужно 192 четвёрки, десятке — 96, так что пол проходит с запасом;
   * упирается он только в цель 1000 уровней (нужно ~12800 связей).
   *
   * Пол постоянный для всех декад. Соблазн опускать его к поздним уровням есть —
   * в записи оригинала редкость слов даёт +0.68 к D, — но жалобы пришли как раз
   * на уровни 17 и 20, то есть поздние. Сложность растёт числом категорий,
   * мета-цепями, ловушками и лимитом ходов, а не незнакомыми словами.
   *
   * ВАЖНО: с появлением регистра слова (`maxWordRegister` ниже) этот пол
   * оставлен только как страховка на неразмеченной базе. Частотность оказалась
   * негодным признаком: `congestion` 3.66 отвергнут, а `carrot` 3.62 и
   * `omelet` 2.63 безупречны. Держать оба фильтра одновременно вредно — пол
   * выбрасывал `omelet`, `radish`, `mop` и `bagel` вместе с мусором, — поэтому
   * при размеченной базе он опускается до нуля.
   */
  minWordZipf: number;
  /**
   * Предельный регистр слова: 0 только бытовые, 1 бытовые и пассивные,
   * 2 любые. Главный фильтр словаря с 02.08.
   *
   * Заменяет пол частотности. Замер: слов класса `everyday` 4924, играбельных
   * связей от них 10788 (против 8923 выше zipf 3.75), категорий, способных дать
   * четвёрку целиком из бытовых слов, — 980 (против 931 под порогом и 780 под
   * zipf 4.0). То есть признак даёт и лучшее качество, и БОЛЬШУЮ ёмкость: он не
   * режет `omelet` 2.63 и `radish` 2.78 за компанию с `quail` 3.13.
   *
   * Слово без разметки (`e == null`) фильтр проходит: иначе снимок, собранный до
   * шага 010, перестал бы генерироваться вовсе.
   */
  maxWordRegister: 0 | 1 | 2;
  /**
   * Пол веса слова: тот же фильтр, что регистр, но для базы без разметки.
   *
   * Читается только там, где вес есть (словарь игры, снимок 2.1). На авторской разметке
   * и на словаре оригинала поля `w` у слов нет, гейт молчит, и ни один ранее
   * собранный пакет от его появления не меняется.
   *
   * Почему порог для оценки СТРОЖЕ, чем для разметки. Размеченное бытовое слово
   * имеет вес 1.00, пассивное 0.55; порог 0.70 на декадах 1-50 пропускает
   * первое и отсекает второе — ровно то же, что делает `maxWordRegister = 0`.
   * Но неразмеченное слово с оценкой 0.70 — это не «бытовое», а «похоже на
   * бытовое с вероятностью 0.83» (замер в SnapshotWord.w). Планка одна, а
   * требование к оценке из-за этого выходит выше: из 8786 неразмеченных слов
   * выгрузки её проходят 480, то есть чужой словарь входит в ранние декады
   * только самой расхожей своей частью — `books`, `wine`, `canada`, `beer`.
   */
  minWordWeight: number;
  /** целевая медиана частотности слов уровня */
  /**
   * Куда в пуле категории целится декада: 0 — верх (самые расхожие слова
   * каждой категории), 1 — низ. Это тот же рычаг, что раньше держала
   * `zipfMedianTarget`, но перевёрнутый правильной стороной: раньше цель
   * стояла НА СЛОВЕ и наказывала расхожее слово за частотность, теперь она
   * стоит на УРОВНЕ, а слово выбирается местом в своей категории.
   * `zipfMedianTarget` остаётся мерой приёмки: чем блок обязан оказаться.
   */
  poolRankTarget?: number | null;
  zipfMedianTarget: number;
  /** целевой 25-й процентиль частотности */
  zipfP25Target: number;
  /** минимальная доля уровня, видимая на поле одновременно */
  visibleShareMin: number;
  /** коридор повторов слова из прошлых уровней в ДРУГОЙ категории */
  repeatRange: [number, number];
  /** первый уровень блока — туториал (только для блока, начинающегося с 1) */
  tutorialFirstLevel: boolean;
}

/**
 * Допуски по частотности.
 *
 * Важное различие, на котором легко ошибиться. Цель из таблицы декад (медиана
 * 4.35 для L1-10) — это медиана ВСЕЙ декады, а не каждого уровня. Замер по
 * референсу: внутри L1-10 медианы отдельных уровней идут 4.92, 4.42, 4.53, 4.66,
 * 4.04, 4.07, 4.65, 3.97, 3.95, 4.42 — разброс почти целый zipf, sd 0.32.
 * Поэтому на уровень допуск широкий (≈2σ), а строгий держится на блоке целиком.
 */
export const ZIPF_BLOCK_TOLERANCE = 0.15;
export const ZIPF_LEVEL_TOLERANCE = 0.65;

export type LevelRole = 'tutorial' | 'entry' | 'growth' | 'recovery' | 'peak' | 'spike' | 'exit';

export interface LevelPlan {
  levelId: number;
  /** позиция в блоке, 1-based */
  position: number;
  role: LevelRole;
  categoryCount: number;
  metaCount: number;
  metaDepthTarget: number;
  rareTarget: number;
  trapTarget: number;
  chainCount: number;
  /** игровой модификатор уровня — один на партию, назначается кривой блока */
  modifier: LevelModifier;
  /** целевой коридор оценок */
  targetDifficulty: [number, number];
  targetInterest: [number, number];
  /** K из формулы лимита ходов (TARGET_GAME_OBSERVATIONS §3); null = без лимита */
  moveLimitK: number | null;
  /**
   * Куда в пуле категории целится уровень: 0 — верх (самые расхожие слова
   * категории), 1 — низ. Приходит из профиля декады и двигается ролью уровня:
   * передышка берёт выше, пик — ниже. null = ось выключена (пресет без гейтов
   * или снимок без ранжирования).
   */
  poolRankTarget?: number | null;
}

